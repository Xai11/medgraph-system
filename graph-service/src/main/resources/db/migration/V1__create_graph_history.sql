CREATE TABLE graph_snapshot (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id varchar(64) NOT NULL,
    batch_id bigint NOT NULL,
    changed_at timestamptz NOT NULL,
    facts jsonb NOT NULL,
    UNIQUE (object_id, batch_id)
);

CREATE TABLE fact_lifecycle_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fact_id uuid NOT NULL,
    object_id varchar(64) NOT NULL,
    batch_id bigint NOT NULL,
    changed_at timestamptz NOT NULL,
    event_type varchar(24) NOT NULL,
    previous_position integer,
    position integer,
    UNIQUE (fact_id, batch_id),
    CHECK (previous_position IS NULL OR previous_position > 0),
    CHECK (position IS NULL OR position > 0),
    CHECK (
        (event_type = 'REGISTERED' AND previous_position IS NULL AND position IS NOT NULL)
        OR (event_type = 'POSITION_CHANGED' AND previous_position IS NOT NULL
            AND position IS NOT NULL AND previous_position <> position)
        OR (event_type = 'DELETED' AND previous_position IS NOT NULL AND position IS NULL)
    )
);
